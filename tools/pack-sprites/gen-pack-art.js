// Turns build/pack-art/ids.json (uploaded asset ids) into MinePackArt.luau,
// the game's lookup for the 19 sets' pack sprites, set icons and rarity icons.
// Re-run after re-uploading; do not hand-edit MinePackArt.luau.
//
//   node tools/pack-sprites/gen-pack-art.js
const fs = require("fs");
const path = require("path");
const SETS = require("./sets.js");

const ROOT = path.join(__dirname, "..", "..");
const ids = require(path.join(ROOT, "build", "pack-art", "ids.json"));
const OUT = path.join(ROOT, "src", "ReplicatedStorage", "Mine", "Shared", "MinePackArt.luau");

const BANDS = ["1-2star", "2.5-3.5star", "4-5star"];
const RARITIES = ["Common", "Uncommon", "Rare", "Epic", "Legendary", "Mythic", "Divine", "Exotic"];

const rgb = hex => [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16));
const scale = (c, k) => c.map(v => Math.round(v * k));
const color3 = c => `Color3.fromRGB(${c.join(", ")})`;

const missing = [];
const setLines = SETS.map(s => {
  const packs = ids.packs[s.file] || {};
  const sprites = BANDS.map(b => packs[b] || (missing.push(`${s.file} ${b}`), ""));
  const icon = ids.sets[s.file] || (missing.push(`${s.file} set icon`), "");
  const a = rgb(s.accent);
  return [
    `\t${s.key} = {`,
    `\t\tsprites = { "${sprites.join('", "')}" },`,
    `\t\ticon = "${icon}",`,
    `\t\taccent = ${color3(a)},`,
    `\t\tsecondary = ${color3(scale(a, 0.6))},`,
    `\t\tprimary = ${color3(scale(a, 0.32))},`,
    `\t},`,
  ].join("\n");
});
const rarityLines = RARITIES.map(r => `\t${r} = "${ids.rarity[r] || (missing.push(`${r} rarity`), "")}",`);
if (missing.length) {
  console.error("MISSING ids for: " + missing.join(", "));
  process.exit(1);
}

const out = `--[[
	PACK ART for the 19 sets. Generated by tools/pack-sprites/gen-pack-art.js
	from build/pack-art/ids.json -- do not hand-edit.

	Three 3D pack sprites per set (732x1024), one per star band, so a pack's
	wrapper shows its set and roughly how good it is; the stars and the grade
	themselves are drawn by the UI. Plus a 512x512 medallion per set and a gem per
	card rarity. Uploaded 2026-10-10 by the owner's account and shared with the
	group experience (wiki: code/assets-and-uploads).

	Keyed by set key (MineSetPacks / MineSetPets), which is save data.
]]
local MinePackArt = {}

-- Sprite band by a pack's STARS, the owner's bands: up to 2 stars -> 1,
-- 2.5 to 3.5 -> 2, 4 and up -> 3. Read from the rating, not the slot, so a
-- pack re-rated to 2.5 / 3.5 / 4.5 picks up the right sprite by itself.
function MinePackArt.bandOfStars(stars)
	stars = tonumber(stars) or 1
	if stars <= 2 then
		return 1
	elseif stars < 4 then
		return 2
	end
	return 3
end

-- Fallback when MineSetPacks cannot be read: its default STARS by slot.
MinePackArt.STARS_OF_LEVEL = { 1, 1.5, 2, 3, 4, 5 }

local function starsOf(packId, level)
	local ok, SetPacks = pcall(function()
		return require(script.Parent:WaitForChild("MineSetPacks", 5))
	end)
	local def = ok and type(SetPacks) == "table" and SetPacks.PACK_BY_ID and SetPacks.PACK_BY_ID[packId]
	if def and tonumber(def.stars) then
		return tonumber(def.stars)
	end
	local stars = ok and type(SetPacks) == "table" and SetPacks.STARS and SetPacks.STARS[level]
	return tonumber(stars) or MinePackArt.STARS_OF_LEVEL[level]
end

MinePackArt.SETS = {
${setLines.join("\n")}
}

MinePackArt.RARITY = {
${rarityLines.join("\n")}
}

--[[
	The MinePackFX art row for a set pack id ("<setKey>_pack_<1..6>"), or nil.
	Parsed from the id rather than read from MineSetPacks, so it works before
	the set pets are generated and for any pack a save already holds.
]]
function MinePackArt.packArt(packId)
	packId = tostring(packId or "")
	local setKey, level = string.match(packId, "^(.-)_pack_(%d)$")
	local set = setKey and MinePackArt.SETS[setKey]
	level = tonumber(level)
	if not (set and level and level >= 1 and level <= 6) then
		return nil
	end
	local band = MinePackArt.bandOfStars(starsOf(packId, level))
	return {
		primary = set.primary,
		secondary = set.secondary,
		accent = set.accent,
		image = set.sprites[band],
	}
end

function MinePackArt.setIcon(setKey)
	local set = MinePackArt.SETS[setKey]
	return set and set.icon or nil
end

function MinePackArt.rarityIcon(rarity)
	return MinePackArt.RARITY[rarity]
end

return MinePackArt
`;
fs.writeFileSync(OUT, out.replace(/\n/g, "\r\n"));
console.log(`wrote ${path.relative(ROOT, OUT)}: ${SETS.length} sets, ${SETS.length * 3} sprites, ${RARITIES.length} rarity icons`);
