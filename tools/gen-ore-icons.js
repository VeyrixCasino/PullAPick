// Turns build/icons/ids.json (name -> uploaded assetId) into the Luau lookup.
// Re-run after uploading more icons; do not hand-edit MineOreIcons.luau.
const fs = require("fs");
const ids = require("../build/icons/ids.json");

// tier=id|Name,... straight from MineConfig.ORES, so the module can never
// disagree with the live roster about which ore is which.
const ROSTER = fs.readFileSync(__dirname + "/../build/icons/roster.txt", "utf8").trim();
const rows = ROSTER.split(",").map((s) => {
	const [tier, rest] = s.split("=");
	const [id, name] = rest.split("|");
	return { tier: Number(tier), id, name };
});

const missing = [];
const lines = rows.map((r) => {
	const icon = ids[r.name];
	const box = ids[r.name + "Case"];
	if (!icon || !box) missing.push(r.name);
	return `\t${r.id} = { icon = "rbxassetid://${icon}", case = "rbxassetid://${box}" },`;
});
if (missing.length) {
	console.error("MISSING icons for: " + missing.join(", "));
	process.exit(1);
}

const out = `--[[
	ORE ICONS. Generated by tools/gen-ore-icons.js -- do not hand-edit.

	512x512 uploaded art, one icon and one case per ore, keyed by ORE ID (not
	by name: names get retyped, ids are load-bearing in the datastore).

	Why uploaded assets rather than MineOreArt's packed-pixel pipeline: that one
	rebuilds 64x64 faces at runtime via EditableImage, which is right for
	procedural block faces. These are 512x512 authored art -- 43 million pixels
	across 164 images -- so packing them would be hundreds of megabytes of Luau.
	Uploaded images are CDN-served and cost nothing at runtime.

	${rows.length} ores x 2 = ${rows.length * 2} assets.
]]

local MineOreIcons = {}

MineOreIcons.BY_ID = {
${lines.join("\n")}
}

-- Nil rather than a placeholder: callers decide what a missing icon looks
-- like, and a silent fallback hides a roster/art mismatch.
function MineOreIcons.icon(oreId)
	local row = MineOreIcons.BY_ID[tostring(oreId or "")]
	return row and row.icon or nil
end

function MineOreIcons.case(oreId)
	local row = MineOreIcons.BY_ID[tostring(oreId or "")]
	return row and row.case or nil
end

return MineOreIcons
`;
fs.writeFileSync(__dirname + "/../src/ReplicatedStorage/Mine/Shared/MineOreIcons.luau", out);
console.log(`wrote MineOreIcons.luau: ${rows.length} ores, ${rows.length * 2} assets`);
