// Turns build/charm-icons/ids.json (charm id -> uploaded assetId) into the Luau
// lookup. Re-run after uploading more icons; do not hand-edit MineCharmIcons.luau.
//
// The art itself comes from tools/icons/gen-charm-art.js. This is the step after
// uploading, and uploading is manual on purpose: every asset must be created as
// the Mine For Cards group (docs/TODO.md section 7), which no agent here can do.
//
// ids.json is { "<charmId>": <assetId>, ... } -- keyed by the charm id, not the
// name, because ids are what the datastore holds and names get retyped.
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const ICONS = path.join(ROOT, "build/charm-icons");
const MANIFEST = path.join(ICONS, "manifest.json");
const IDS = path.join(ICONS, "ids.json");
const OUT = path.join(ROOT, "src/ReplicatedStorage/Mine/Shared/MineCharmIcons.luau");

if (!fs.existsSync(MANIFEST)) {
  console.error("no build/charm-icons/manifest.json — run tools/icons/gen-charm-art.js first");
  process.exit(1);
}
const manifest = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));

if (!fs.existsSync(IDS)) {
  console.error(
    `no build/charm-icons/ids.json yet.\n` +
    `  ${manifest.length} icons are drawn in build/charm-icons/.\n` +
    `  Upload them AS THE GROUP (35326298), then write ids.json as\n` +
    `  { "<charmId>": <assetId>, ... } and re-run this.`
  );
  process.exit(1);
}
const ids = JSON.parse(fs.readFileSync(IDS, "utf8"));

const missing = [];
const lines = manifest.map((m) => {
  const asset = ids[m.id];
  if (!asset) missing.push(m.id);
  return `\t${m.id} = "rbxassetid://${asset}",`;
});
if (missing.length) {
  console.error(`MISSING ids for ${missing.length} charm(s): ${missing.slice(0, 8).join(", ")}${missing.length > 8 ? ", ..." : ""}`);
  process.exit(1);
}

const shapes = [...new Set(manifest.map((m) => m.shape))].sort();
const out = `--[[
	CHARM ICONS. Generated by tools/gen-charm-icons.js -- do not hand-edit.

	One uploaded image per charm, keyed by CHARM ID (not by name: names get
	retyped, ids are load-bearing in the datastore).

	The art is generated rather than authored -- see tools/icons/gen-charm-art.js
	-- and reads as colour for WHICH ORE, glyph for WHAT IT DOES, pips for rarity.
	An ore's two variants therefore share a colour and differ in glyph, which is
	exactly how they differ in play.

	${manifest.length} charms (${manifest.length / 2} ores x 2 variants), ${shapes.length} glyphs.
]]
local MineCharmIcons = {}

MineCharmIcons.BY_ID = {
${lines.join("\n")}
}

-- The icon for a charm id, or nil. Callers should fall back to whatever they
-- draw for an item with no art rather than assuming this is non-nil: an icon
-- can be missing for a charm added before its art is uploaded.
function MineCharmIcons.icon(charmId)
	return MineCharmIcons.BY_ID[tostring(charmId or "")]
end

return MineCharmIcons
`;

fs.writeFileSync(OUT, out);
console.log(`>>> ${manifest.length} charm icons -> ${path.relative(ROOT, OUT)}`);
